from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
from mcp.client import Client
from mcp.server.mcpserver.exceptions import ToolError
from pd_mcp_github.backend import MockBackend
from pd_mcp_github.policy import WritePolicy
from pd_mcp_github.server import build_server

FIXTURES = Path(__file__).resolve().parents[3] / "fixtures"
REPO = "acme/demo-service"
C = "c3d4e5f60718293a4b5c6d7e8f90123456789012"


@pytest.fixture
def backend() -> MockBackend:
    return MockBackend.load(FIXTURES)


async def call(backend: MockBackend, tool: str, args: dict[str, Any]) -> tuple[bool, str, Any]:
    async with Client(build_server(backend)) as client:
        res = await client.call_tool(tool, args)
    return (
        bool(res.is_error),
        "".join(getattr(c, "text", "") for c in res.content),
        res.structured_content,
    )


@pytest.mark.parametrize(
    "name",
    [
        "main",
        "feature/x",
        "pipeline-doctor",
        "pipeline-doctor/",
        "pipeline-doctor/../main",
        "pipeline-doctor//x",
        "pipeline-doctor/x.lock",
        "Pipeline-Doctor/x",
        "pipeline-doctor/a b",
    ],
)
async def test_create_branch_refuses_unsafe_names(backend: MockBackend, name: str) -> None:
    err, text, _ = await call(backend, "create_branch", {"repo": REPO, "name": name, "from_sha": C})
    assert err, text
    assert backend.branches == {}


async def test_create_branch_refuses_default_branch_explicitly(backend: MockBackend) -> None:
    err, text, _ = await call(
        backend, "create_branch", {"repo": REPO, "name": "main", "from_sha": C}
    )
    assert err and "default branch" in text


async def test_create_branch_ok_and_no_duplicates(backend: MockBackend) -> None:
    args = {"repo": REPO, "name": "pipeline-doctor/fix-pricing-12", "from_sha": C}
    err, _, data = await call(backend, "create_branch", args)
    assert not err and data["branch"] == "pipeline-doctor/fix-pricing-12" and data["from_sha"] == C
    err, text, _ = await call(backend, "create_branch", args)
    assert err and "already exists" in text


async def make_branch_with_commit(
    backend: MockBackend, head: str = "pipeline-doctor/fix-pricing-12"
) -> str:
    await call(backend, "create_branch", {"repo": REPO, "name": head, "from_sha": C})
    err, text, _ = await call(
        backend,
        "commit_files",
        {
            "repo": REPO,
            "branch": head,
            "message": "Fix discount",
            "files": [
                {
                    "path": "app/pricing.py",
                    "content": "def apply_discount(p, r):\n    return p * (1 - r)\n",
                }
            ],
        },
    )
    assert not err, text
    return head


async def test_pull_request_is_draft_targets_default_and_has_footer(backend: MockBackend) -> None:
    head = await make_branch_with_commit(backend)
    err, _, data = await call(
        backend,
        "open_draft_pull_request",
        {
            "repo": REPO,
            "head": head,
            "base": "main",
            "title": "Fix discount",
            "body": "Restores (1 - rate).",
        },
    )
    assert not err and data["draft"] is True and data["number"] == 1
    pr = backend.pull_requests[0]
    assert pr["draft"] is True and "Generated by Pipeline Doctor" in str(pr["body"])


