"""Tickets: render from validated data, write through the Jira MCP server, assign via CODEOWNERS.

This step is plain code, not an LLM. Nothing in it needs judgment (a template over structured,
already-validated results plus a lookup by fingerprint), and keeping the model out means the writes
are fully policy-controlled, testable byte for byte, and cannot be steered by text hidden in a log
or a commit message. It still passes through the same tool policy and audit log as an agent,
under the name ``ticket_agent``.

Every string that came from a build, a commit or a model is scrubbed, stripped of Jira markup
that could change the layout (macros, mentions) and length-capped before it is written.
"""

from __future__ import annotations

import re
import sys
from collections.abc import Callable
from contextlib import AsyncExitStack
from typing import Any, Literal

from mcp.client import Client
from pydantic import BaseModel

from pipeline_doctor_agent.audit import AuditLog
from pipeline_doctor_agent.codeowners import Rule, choose_assignee
from pipeline_doctor_agent.fix.models import FixOutcome
from pipeline_doctor_agent.investigator import InvestigationResult
from pipeline_doctor_agent.mcp_calls import PolicySession, ToolCallError, flatten_errors
from pipeline_doctor_agent.policy.gate import Action, suspect_in_range
from pipeline_doctor_agent.policy.tools import RunScope, ToolPolicy
from pipeline_doctor_agent.preprocess import ProcessedFailure
from pipeline_doctor_agent.preprocess.fingerprint import compute_fingerprint
from pipeline_doctor_agent.preprocess.scrub import scrub
from pipeline_doctor_agent.schemas import Category, PipelineFailedEvent
from pipeline_doctor_agent.settings import Settings

AGENT = "ticket_agent"
FOOTER = "_Generated by Pipeline Doctor — please verify._"
MAX_BODY = 19_000  # the Jira tools accept 20,000 / 19,900 characters
MAX_LOG_LINES = 15
ClientFactory = Callable[[], Client]


TicketError = (
    ToolCallError  # a ticket operation failed; the message is retried, finally dead-lettered
)


class TicketOutcome(BaseModel):
    action: Literal["created", "commented", "comment_already_present"]
    issue_key: str
    url: str | None = None
    assignee: str | None = None
    degraded: bool = False


# ---- text safety -----------------------------------------------------------------------------

_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
_BLOCK_MACROS = re.compile(
    r"\{(?:noformat|code|panel|quote|html|color|anchor|include|jira)[^}]*\}", re.I
)


def text(value: str, limit: int = 600) -> str:
    """Single-line text for use inside a sentence or bullet."""
    value = scrub(value).text
    value = _CONTROL.sub("", value).replace("{", "(").replace("}", ")").replace("[~", "[ ~")
    value = re.sub(r"\s+", " ", value).strip().replace("|", "/")
    return value if len(value) <= limit else value[: limit - 3] + "..."


def block(lines: list[str]) -> str:
    """Preformatted block; the closing macro cannot be forged from inside it."""
    safe = [_BLOCK_MACROS.sub("", _CONTROL.sub("", scrub(line).text))[:400] for line in lines]
    return "{noformat}\n" + "\n".join(safe) + "\n{noformat}"


def finish(body: str, limit: int = MAX_BODY) -> str:
    """Last gate before anything leaves the process: scrub the whole body again and cap its size."""
    body = scrub(body).text
    if len(body) <= limit:
        return body
    tail = "\n...(truncated)\n" + FOOTER  # the footer must survive truncation
    return body[: limit - len(tail)] + tail


# ---- rendering -------------------------------------------------------------------------------


def _link(label: str, url: str | None) -> str:
    return f"[{label}|{url}]" if url else label


def _commit_url(settings: Settings, repo: str | None, sha: str | None) -> str | None:
    return f"{settings.github_web_url}/{repo}/commit/{sha}" if repo and sha else None


def _pipeline_lines(
    settings: Settings, event: PipelineFailedEvent, repo: str | None, stage: str | None
) -> list[str]:
    lines = [
        f"* Job: {text(event.job_name, 200)}",
        f"* Build: {_link(f'#{event.build_number}', event.build_url)}",
    ]
    if event.commit_sha:
        lines.append(
            f"* Failing commit: {_link(event.commit_sha[:10], _commit_url(settings, repo, event.commit_sha))}"
        )
    if stage:
        lines.append(f"* Failed stage: {text(stage, 200)}")
    return lines


def next_steps(result: InvestigationResult, pr_url: str | None) -> list[str]:
    d = result.diagnosis
    steps: list[str] = []
    if d.category in {Category.CODE, Category.TEST, Category.DEPENDENCY}:
        if pr_url:
            steps.append(
                f"Review the draft pull request {pr_url} and run the full suite before merging."
            )
        else:
            steps.append(
                "Review the suspect commit and fix the failing behaviour; a human decides the change."
            )
    elif d.category is Category.INFRASTRUCTURE:
        steps.append(
            "Check the health of the service, runner or credential named in the evidence, then re-run the stage."
        )
        steps.append("No code change is expected for this failure.")
    elif d.category is Category.FLAKY:
        steps.append(
            "Do not change code for a single flaky failure; record this occurrence and follow the quarantine process."
        )
    else:
        steps.append(
            "Review the pipeline or application configuration changed since the last green build."
        )
    steps += [
        f"Runbook ({text(s.source, 120)}): {text(s.step, 300)}"
        for s in result.knowledge_findings.runbook_steps
    ]
    return steps


def render_issue(
    settings: Settings,
    result: InvestigationResult,
    *,
    repo: str | None,
    pr_url: str | None,
    owners: list[str],
    previous: list[str],
    fix: FixOutcome | None = None,
) -> tuple[str, str]:
    d, gate, ev = result.diagnosis, result.decision, result.event
    summary = f"[{d.category.value}] {text(ev.job_name, 80)}: {text(d.root_cause, 140)}"
    out: list[str] = [
        "h3. Summary",
        text(d.root_cause, 1000),
        "",
        "h3. Affected pipeline",
        *_pipeline_lines(settings, ev, repo, result.processed.failed_stage),
        "",
        "h3. Classification",
        f"* Category: {d.category.value}",
        f"* Confidence: {d.confidence:.2f}",
        f"* Fixable by a code change: {'yes' if d.fixable else 'no'}",
        "",
        "h3. Root cause",
        text(d.root_cause, 1000),
        "",
        "h3. Evidence",
        *[f"* {text(e, 500)}" for e in d.evidence],
    ]
    if d.suspect_commit:
        out.append(
            f"* Suspect commit: {_link(d.suspect_commit[:10], _commit_url(settings, repo, d.suspect_commit))}"
        )
    if result.processed.error_lines:
        out += ["", "Log excerpt (scrubbed):", block(result.processed.error_lines[:MAX_LOG_LINES])]
    out += ["", "h3. Proposed fix"]
    if pr_url:
        out.append(f"Draft pull request: {pr_url}")
        if fix and fix.verification:
            out.append(
                f"Verified in an isolated sandbox: {text(fix.verification, 300)}. A human must review and merge."
            )
    elif fix is not None and fix.status in {"failed", "error", "skipped"}:
        out.append(
            f"An automatic fix was considered but no pull request was opened: {text(fix.reason, 500)}"
        )
    elif gate.action is Action.FIX:
        out.append("A fix may be attempted automatically; no pull request exists yet.")
    else:
        out.append("No automatic fix was attempted:")
        out += [f"* {text(r, 300)}" for r in gate.reasons]
    out += ["", "h3. Recommended next steps", *[f"* {s}" for s in next_steps(result, pr_url)]]
    kn = result.knowledge_findings
    if kn.similar_incidents:
        out += ["", "h3. Similar past incidents"]
        out += [f"* {text(i.source, 120)}: {text(i.summary, 300)}" for i in kn.similar_incidents]
    if owners:
        out += ["", "h3. Code owners", "* " + ", ".join(text(o, 100) for o in owners)]
    if previous:
        out += ["", f"Previously tracked (closed): {', '.join(text(p, 40) for p in previous)}"]
    out += ["", "h3. Fingerprint", result.fingerprint, "", "----", FOOTER]
    return text(summary, 250), finish("\n".join(out))


def render_comment(
    settings: Settings,
    result: InvestigationResult,
    *,
    repo: str | None,
    pr_url: str | None,
    fix: FixOutcome | None = None,
) -> str:
    d, gate, ev = result.diagnosis, result.decision, result.event
    out = [
        "New occurrence of this failure.",
        *_pipeline_lines(settings, ev, repo, result.processed.failed_stage),
        f"* Category: {d.category.value}, confidence {d.confidence:.2f}",
        f"* Root cause (this run): {text(d.root_cause, 600)}",
        *[f"* Evidence: {text(e, 400)}" for e in d.evidence[:5]],
    ]
    if pr_url:
        out.append(f"* Draft pull request: {pr_url}")
    elif fix is not None and fix.status in {"failed", "error", "skipped"}:
        out.append(f"* No pull request: {text(fix.reason, 500)}")
    elif gate.action is Action.TICKET_ONLY:
        out.append(f"* No automatic fix: {text('; '.join(gate.reasons), 500)}")
    out += [f"* Fingerprint: {result.fingerprint}", "", FOOTER]
    return finish("\n".join(out))


def render_degraded(
    settings: Settings,
    event: PipelineFailedEvent,
    *,
    repo: str | None,
    reason: str,
    processed: ProcessedFailure | None,
    fingerprint: str,
) -> tuple[str, str]:
    stage = processed.failed_stage if processed else None
    out = [
        "h3. Automatic diagnosis was unavailable",
        f"Pipeline Doctor could not complete its analysis ({text(reason, 300)}). This ticket only records the failure; please triage it manually.",
        "",
        "h3. Affected pipeline",
        *_pipeline_lines(settings, event, repo, stage),
    ]
    if processed and processed.error_type:
        out += ["", f"Detected error type: {text(processed.error_type, 200)}"]
    if processed and processed.error_lines:
        out += ["", "Log excerpt (scrubbed):", block(processed.error_lines[:MAX_LOG_LINES])]
    else:
        out += ["", "No log excerpt is available: Jenkins data could not be fetched."]
    out += [
        "",
        "h3. Recommended next steps",
        "* Open the build and read the failing stage.",
        "* Re-run the investigation once the cause of the outage is fixed.",
        "",
        "h3. Fingerprint",
        fingerprint,
        "",
        "----",
        FOOTER,
    ]
    summary = f"[unknown] {text(event.job_name, 80)} #{event.build_number}: automatic diagnosis unavailable"
    return summary, finish("\n".join(out))


# ---- the service -----------------------------------------------------------------------------


def default_jira_client(settings: Settings) -> Client:
    import shlex

    from mcp import StdioServerParameters

    cmd = (
        shlex.split(settings.jira_mcp_command)
        if settings.jira_mcp_command
        else [sys.executable, "-m", "pd_mcp_jira"]
    )
    return Client(
        StdioServerParameters(
            command=cmd[0],
            args=cmd[1:],
            env={"MCP_MODE": settings.mcp_mode, "FIXTURES_DIR": settings.fixtures_dir},
        )
    )


def default_github_client(settings: Settings) -> Client:
    import shlex

    from mcp import StdioServerParameters

    cmd = (
        shlex.split(settings.github_mcp_command)
        if settings.github_mcp_command
        else [sys.executable, "-m", "pd_mcp_github"]
    )
    return Client(
        StdioServerParameters(
            command=cmd[0],
            args=cmd[1:],
            env=settings.github_env(),
        )
    )


class _Session(PolicySession):
    """The ticket identity: policy-checked and audited as ``ticket_agent``."""

    def __init__(self, client: Client, policy: ToolPolicy, audit: AuditLog) -> None:
        super().__init__(client, policy, audit, AGENT)


class TicketService:
    def __init__(
        self,
        settings: Settings,
        *,
        jira: ClientFactory | None = None,
        github: ClientFactory | None = None,
    ) -> None:
        self.settings = settings
        self._jira = jira or (lambda: default_jira_client(settings))
        self._github = github or (lambda: default_github_client(settings))

    @staticmethod
    def degraded_fingerprint(event: PipelineFailedEvent, processed: ProcessedFailure | None) -> str:
        """Stable per job when there are no facts, so repeated outages comment on one ticket."""
        if processed:
            return processed.fingerprint
        return compute_fingerprint(None, f"job:{event.job_name}", "automatic diagnosis unavailable")

    async def record(
        self,
        result: InvestigationResult,
        *,
        pr_url: str | None = None,
        fix: FixOutcome | None = None,
    ) -> TicketOutcome:
        with (
            flatten_errors()
        ):  # report the real error, not an anyio "unhandled errors in a TaskGroup"
            return await self._record(result, pr_url=pr_url, fix=fix)

    async def _record(
        self,
        result: InvestigationResult,
        *,
        pr_url: str | None,
        fix: FixOutcome | None,
    ) -> TicketOutcome:
        pr_url = pr_url or (fix.pr_url if fix else None)
        ev = result.event
        repo = ev.repo or self.settings.github_repo
        audit = AuditLog(run_id=ev.idempotency_key)
        policy = ToolPolicy(RunScope(job_name=ev.job_name, repo=repo))
        async with AsyncExitStack() as stack:
            jira = _Session(await stack.enter_async_context(self._jira()), policy, audit)
            owners: list[str] = []
            assignee: str | None = None
            if repo and suspect_in_range(result.diagnosis, result.code_findings):
                github = _Session(await stack.enter_async_context(self._github()), policy, audit)
                assignee, owners = await self._owners(
                    github, repo, result.diagnosis.suspect_commit or ""
                )

            found = (await jira.call("search_similar_issues", fingerprint=result.fingerprint)).get(
                "issues", []
            )
            open_issues = [i for i in found if i.get("open")]
            closed = [i["key"] for i in found if not i.get("open")]

            if open_issues:
                body = render_comment(self.settings, result, repo=repo, pr_url=pr_url, fix=fix)
                return await self._comment(jira, open_issues[0], body, ev.idempotency_key)

            summary, description = render_issue(
                self.settings,
                result,
                repo=repo,
                pr_url=pr_url,
                owners=owners,
                previous=closed,
                fix=fix,
            )
            try:
                created = await jira.call(
                    "create_issue",
                    summary=summary,
                    description=description,
                    fingerprint=result.fingerprint,
                    category=result.diagnosis.category.value,
                    **({"assignee": assignee} if assignee else {}),
                )
            except TicketError as exc:
                if "already tracks this fingerprint" not in str(exc):
                    raise
                # Lost a race with another worker: the ticket exists now, so comment on it.
                again = (
                    await jira.call("search_similar_issues", fingerprint=result.fingerprint)
                ).get("issues", [])
                still_open = [i for i in again if i.get("open")]
                if not still_open:
                    raise
                body = render_comment(self.settings, result, repo=repo, pr_url=pr_url, fix=fix)
                return await self._comment(jira, still_open[0], body, ev.idempotency_key)
            return TicketOutcome(
                action="created",
                issue_key=created["key"],
                url=created.get("url"),
                assignee=assignee,
            )

    async def record_degraded(
        self, event: PipelineFailedEvent, reason: str, processed: ProcessedFailure | None
    ) -> TicketOutcome:
        with flatten_errors():
            return await self._record_degraded(event, reason, processed)

    async def _record_degraded(
        self, event: PipelineFailedEvent, reason: str, processed: ProcessedFailure | None
    ) -> TicketOutcome:
        repo = event.repo or self.settings.github_repo
        fingerprint = self.degraded_fingerprint(event, processed)
        audit = AuditLog(run_id=event.idempotency_key)
        async with AsyncExitStack() as stack:
            jira = _Session(
                await stack.enter_async_context(self._jira()),
                ToolPolicy(RunScope(job_name=event.job_name, repo=repo)),
                audit,
            )
            found = (await jira.call("search_similar_issues", fingerprint=fingerprint)).get(
                "issues", []
            )
            open_issues = [i for i in found if i.get("open")]
            summary, description = render_degraded(
                self.settings,
                event,
                repo=repo,
                reason=reason,
                processed=processed,
                fingerprint=fingerprint,
            )
            if open_issues:
                return await self._comment(
                    jira, open_issues[0], description, event.idempotency_key, degraded=True
                )
            created = await jira.call(
                "create_issue",
                summary=summary,
                description=description,
                fingerprint=fingerprint,
                category="unknown",
            )
            return TicketOutcome(
                action="created", issue_key=created["key"], url=created.get("url"), degraded=True
            )

    async def _comment(
        self, jira: _Session, issue: dict[str, Any], body: str, key: str, *, degraded: bool = False
    ) -> TicketOutcome:
        res = await jira.call("add_comment", issue_key=issue["key"], body=body, idempotency_key=key)
        return TicketOutcome(
            action="comment_already_present" if res.get("duplicate") else "commented",
            issue_key=issue["key"],
            url=issue.get("url"),
            degraded=degraded,
        )

    async def _owners(self, github: _Session, repo: str, sha: str) -> tuple[str | None, list[str]]:
        """Best effort: a missing CODEOWNERS file or a GitHub hiccup must not block the ticket."""
        try:
            files = [
                f["path"]
                for f in (await github.call("get_commit_diff", repo=repo, sha=sha)).get("files", [])
            ]
            entries = (await github.call("get_codeowners", repo=repo)).get("entries", [])
        except TicketError:
            return None, []
        rules = [Rule(e["pattern"], tuple(e["owners"])) for e in entries]
        return choose_assignee(files, rules)
