async def test_losing_a_creation_race_falls_back_to_a_comment(env: Env, make_result: Any) -> None:
    """Two workers search at the same time, both see nothing, one creates first: the loser must comment."""
    real = env.jira.search_by_fingerprint
    calls = {"n": 0}

    def flaky_search(fp: str) -> list[Any]:
        calls["n"] += 1
        return (
            [] if calls["n"] == 1 else real(fp)
        )  # the first search misses the other worker's ticket

    env.jira.search_by_fingerprint = flaky_search  # type: ignore[method-assign]
    out = await env.service.record(make_result(fingerprint=OPEN_FP))
    assert out.action == "commented" and out.issue_key == "DEMO-7" and len(env.jira.issues) == 2


