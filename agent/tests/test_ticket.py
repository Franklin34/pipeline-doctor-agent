async def test_redelivery_never_duplicates_tickets_or_comments(env: Env, make_result: Any) -> None:
    result = make_result(fingerprint="aaaa1111bbbb2222")
    first = await env.service.record(result)  # creates
    second = await env.service.record(
        result
    )  # the same event again, e.g. a redelivery after a crash
    third = await env.service.record(result)
    assert [o.action for o in (first, second, third)] == [
        "created",
        "commented",
        "comment_already_present",
    ]
    assert first.issue_key == second.issue_key == third.issue_key
    assert len([i for i in env.jira.issues.values() if i.fingerprint == "aaaa1111bbbb2222"]) == 1
    assert len(env.jira.issues[first.issue_key].comments) == 1


