EVENT = PipelineFailedEvent(
    idempotency_key="demo-service/main:12",
    job_name="demo-service/main",
    build_number=12,
    repo="acme/demo-service",
    build_url="https://jenkins.example/job/demo-service/main/12/",
)


async def test_fallback_ticket_has_the_scrubbed_excerpt_and_unknown_category(
    env: Env, make_result: Any
) -> None:
    processed = make_result(error_lines=["E   assert 10 == 90", f"ERROR: token={GH}"]).processed
    out = await env.service.record_degraded(EVENT, "budget_exceeded: token budget", processed)
    assert out.action == "created" and out.degraded
    issue = env.jira.issues[out.issue_key]
    assert issue.category == "unknown" and issue.summary.startswith(
        "[unknown] demo-service/main #12"
    )
    assert (
        "Automatic diagnosis was unavailable" in issue.description
        and "assert 10 == 90" in issue.description
    )
    assert GH not in issue.description and issue.description.rstrip().endswith(FOOTER)
    again = await env.service.record_degraded(
        EVENT, "timeout", processed
    )  # the next outage comments
    assert again.action == "commented" and again.issue_key == out.issue_key


async def test_fallback_without_any_facts_still_creates_one_stable_ticket(env: Env) -> None:
    a = await env.service.record_degraded(EVENT, "facts_unavailable: jenkins down", None)
    other_build = EVENT.model_copy(
        update={"idempotency_key": "demo-service/main:13", "build_number": 13}
    )
    b = await env.service.record_degraded(other_build, "facts_unavailable: jenkins down", None)
    assert (
        a.action == "created" and b.action == "commented" and a.issue_key == b.issue_key
    )  # same job -> same ticket
    assert "No log excerpt is available" in env.jira.issues[a.issue_key].description


