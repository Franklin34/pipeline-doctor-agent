async def test_ticket_agent_cannot_call_tools_outside_its_allowlist(env: Env) -> None:
    from pipeline_doctor_agent.audit import AuditLog
    from pipeline_doctor_agent.policy.tools import RunScope, ToolPolicy

    audit = AuditLog("t")
    async with Client(github_server(env.github)) as client:
        session = _Session(
            client, ToolPolicy(RunScope("demo-service/main", "acme/demo-service")), audit
        )
        with pytest.raises(TicketError, match="refused by policy"):
            await session.call(
                "create_branch", repo="acme/demo-service", name="main", from_sha="c3d4e5f"
            )
        with pytest.raises(TicketError, match="refused by policy"):
            await session.call("get_codeowners", repo="evil/other")
    assert [r.status for r in audit.records] == ["blocked", "blocked"]
    assert env.github.branches == {}


