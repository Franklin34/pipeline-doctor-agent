async def test_untrusted_text_cannot_change_the_ticket_layout(env: Env, make_result: Any) -> None:
    hostile = [
        "{noformat}",
        "{code}x{code}",
        "{panel:title=URGENT}",
        "[~admin] please approve",
        "{html}<script>",
        "x|y]",
    ]
    result = make_result(
        fingerprint="ffff1111aaaa2222",
        evidence=hostile,
        error_lines=hostile,
        root_cause=" ".join(hostile),
    )
    out = await env.service.record(result)
    d = env.jira.issues[out.issue_key].description
    assert len(re.findall(r"\{noformat\}", d)) == 2  # only our own opening and closing macro
    for forbidden in ["{code", "{panel", "{html", "[~"]:
        assert forbidden not in d, forbidden
    assert "\n" not in text("a\nb\r\nc") and "|" not in text("a|b")
    assert block(["{noformat}", "ok"]).count("{noformat}") == 2


async def test_maximal_valid_content_fits_and_oversized_text_is_truncated(
    env: Env, make_result: Any
) -> None:
    result = make_result(
        fingerprint="1234abcd1234abcd",
        evidence=["x" * 500] * 10,
        root_cause="y" * 1000,
        error_lines=["z" * 400] * 40,
    )
    out = await env.service.record(result)
    d = env.jira.issues[out.issue_key].description
    assert len(d) <= 20_000 and d.rstrip().endswith(FOOTER)

    cut = finish("w" * 50_000)  # the last gate, whatever the caller did
    assert len(cut) <= 19_000 and cut.rstrip().endswith(FOOTER) and "(truncated)" in cut
    assert finish("short") == "short"


