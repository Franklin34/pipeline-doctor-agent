async def test_new_issue_follows_the_template(env: Env, make_result: Any) -> None:
    result = make_result(fingerprint="aaaa1111bbbb2222")
    out = await env.service.record(result)
    assert out.action == "created" and out.issue_key.startswith("DEMO-") and out.assignee == "dev1"

    issue = env.jira.issues[out.issue_key]
    assert issue.summary.startswith("[code] demo-service/main: apply_discount returns")
    assert (
        issue.fingerprint == "aaaa1111bbbb2222"
        and issue.category == "code"
        and issue.assignee == "dev1"
    )
    assert "pipeline-doctor" in issue.labels
    d = issue.description
    for heading in [
        "Summary",
        "Affected pipeline",
        "Classification",
        "Root cause",
        "Evidence",
        "Proposed fix",
        "Recommended next steps",
        "Code owners",
        "Fingerprint",
    ]:
        assert f"h3. {heading}" in d, heading
    assert "[#12|https://jenkins.example/job/demo-service/main/12/]" in d  # build link
    assert (
        "https://github.com/acme/demo-service/commit/c3d4e5f60718293a4b5c6d7e8f90123456789012" in d
    )  # commit link
    assert "Confidence: 0.92" in d and "Category: code" in d and "aaaa1111bbbb2222" in d
    assert (
        "* @dev1, @acme/billing" in d
    )  # owners are listed even though the team cannot be assigned
    assert "assert 10.0 == 90.0" in d and "{noformat}" in d  # scrubbed log excerpt
    assert d.rstrip().endswith(FOOTER) and "Generated by Pipeline Doctor — please verify" in d


