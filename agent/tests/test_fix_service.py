async def test_the_mcp_server_still_refuses_protected_paths_even_if_the_patch_rules_were_bypassed(
    result: Any,
) -> None:
    env = Env([])
    with pytest.raises(ToolCallError, match="protected path"):
        await env.service.publisher.publish(
            result,
            "acme/demo-service",
            "c3d4e5f60718293a4b5c6d7e8f90123456789012",
            {".github/workflows/ci.yml": "name: pwn\n"},
            "[Pipeline Doctor] sneaky",
            "body",
            "msg msg",
        )
    assert env.github.pull_requests == [] and env.github.commits == []


async def test_publishing_twice_reuses_the_branch_and_the_pull_request(result: Any) -> None:
    env = Env([])
    args = (
        result,
        "acme/demo-service",
        "c3d4e5f60718293a4b5c6d7e8f90123456789012",
        {"app/pricing.py": "def f():\n    return 1\n"},
        "[Pipeline Doctor] fix",
        "body",
        "fix it now",
    )
    first = await env.service.publisher.publish(*args)
    second = await env.service.publisher.publish(*args)  # a redelivery after a crash
    assert first == second and len(env.github.pull_requests) == 1


async def test_pull_request_text_is_scrubbed(make_result: Any) -> None:
    poisoned = make_result(
        fingerprint="aaaa1111bbbb2222",
        failed_tests=[("tests.test_pricing", "test_apply_discount")],
        root_cause=f"leaked token {GH} in config",
        evidence=[f"password=hunter2hunter2 {GH}"],
    )
    env = Env([reply(FIXED)])
    out = await env.service.attempt(poisoned)
    assert out.status == "pr_opened"
    [pr] = env.github.pull_requests
    assert GH not in str(pr["body"]) + str(pr["title"]) and "hunter2hunter2" not in str(pr["body"])
