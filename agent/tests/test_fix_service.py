async def test_a_correct_first_proposal_opens_a_draft_pull_request(result: Any) -> None:
    env = Env([reply(FIXED)])
    out = await env.service.attempt(result)

    assert (
        out.status == "pr_opened"
        and out.attempts == 1
        and out.pr_url
        and out.branch == "pipeline-doctor/fix-aaaa1111-b12"
    )
    assert env.sandbox.runs == 2 and env.sandbox.prepared == [
        "pytest==9.2.0\n"
    ]  # baseline + the one proposal
    assert len(env.llm.seen_messages) == 1
    # what reached GitHub
    assert env.github.branch_files["acme/demo-service"][out.branch]["app/pricing.py"].endswith(
        "return price * (1 - rate)\n"
    )
    assert list(env.github.branch_files["acme/demo-service"][out.branch]) == [
        "app/pricing.py"
    ]  # only the changed file
    [pr] = env.github.pull_requests
    assert pr["draft"] is True and pr["base"] == "main" and pr["head"] == out.branch
    body = str(pr["body"])
    assert (
        "```" not in body and "~~~~diff" in body and "+    return price * (1 - rate)" in body
    )  # the real diff
    assert "2 of 3 tests failing" in body and "all 3 tests pass" in body and "no network" in body
    assert (
        "A human must review" in body
        and "aaaa1111bbbb2222" in body
        and "Generated by Pipeline Doctor" in body
    )
    assert "isolated sandbox" in out.verification


