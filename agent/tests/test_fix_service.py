def proposal(
    old: str = "return price * rate",
    new: str = "return price * (1 - rate)",
    path: str = "app/pricing.py",
    why: str = "try this change",
) -> dict[str, Any]:
    return {"explanation": why, "edits": [{"path": path, "old_text": old, "new_text": new}]}


WRONG = proposal(new="return price * rate * 2", why="double it")


class Env:
    def __init__(
        self,
        scripts: list[dict[str, Any]],
        *,
        category: str = "code",
        settings: Settings | None = None,
        sandbox: FakeSandbox | None = None,
        source: Any = None,
    ) -> None:
        self.settings = settings or Settings(
            fix_enabled=True, repos_dir=str(FIXTURES / "repos"), fix_timeout_s=30
        )
        self.github = GitHubMock.load(FIXTURES)
        self.llm = ScriptedLlm(scripts={"fix_agent": list(scripts)})
        self.sandbox = sandbox or FakeSandbox()
        self.service = FixService(
            self.settings,
            source=source or LocalRepoSource(FIXTURES / "repos"),
            sandbox=self.sandbox,
            proposer_factory=lambda guard: AdkProposer(self.llm, guard),
            github=lambda: Client(github_server(self.github)),
        )
        self.category = category


